const fs = require("node:fs");
const path = require("node:path");
const JSZip = require("jszip");
const XLSX = require("xlsx");

function csvEscape(value) {
    const text = String(value ?? "");
    if (/[",\n\r]/.test(text)) return `"${text.replace(/"/g, '""')}"`;
    return text;
}

function toOutputHeader(column) {
    const normalized = String(column || "").replace(/\s*\*\s*/g, "").trim();
    if (normalized === "TSS ID") return "TSS ID(s)";
    return normalized;
}

function rowsToCsvBuffer(rows, columns) {
    const displayColumns = columns.map(toOutputHeader);
    const lines = [displayColumns.map(csvEscape).join(",")];
    for (const row of rows) {
        lines.push(columns.map((c) => csvEscape(row[c] || "")).join(","));
    }
    return Buffer.from(`${lines.join("\n")}\n`, "utf8");
}

function rowsToXlsxBuffer(rows, columns) {
    const sanitizeXlsxCell = (value) => {
        const text = String(value ?? "");
        return text.length > 32767 ? text.slice(0, 32767) : text;
    };
    const displayColumns = columns.map(toOutputHeader);
    const data = [displayColumns, ...rows.map((row) => columns.map((c) => sanitizeXlsxCell(row[c] || "")))];
    const ws = XLSX.utils.aoa_to_sheet(data);
    ws["!cols"] = displayColumns.map(() => ({ wch: 24 }));
    const wb = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(wb, ws, "data");
    return XLSX.write(wb, { type: "buffer", bookType: "xlsx" });
}

function chunkRows(rows, splitEvery) {
    if (!splitEvery) return [rows];
    const chunks = [];
    for (let i = 0; i < rows.length; i += splitEvery) {
        chunks.push(rows.slice(i, i + splitEvery));
    }
    return chunks;
}

function addFilesToZip(zip, folderName, baseName, rows, columns, splitEvery = null, format = "xlsx") {
    const chunks = chunkRows(rows, splitEvery);
    const ext = format === "csv" ? ".csv" : ".xlsx";
    const makeBuf = (chunk) => (format === "csv" ? rowsToCsvBuffer(chunk, columns) : rowsToXlsxBuffer(chunk, columns));

    if (chunks.length === 1) {
        zip.file(`${folderName}/${baseName}${ext}`, makeBuf(chunks[0]));
    } else {
        chunks.forEach((chunk, idx) => {
            zip.file(`${folderName}/${baseName}_${String(idx + 1).padStart(3, "0")}${ext}`, makeBuf(chunk));
        });
    }
}

function getMigrationInstructions(targetId = "shopmonkey") {
    const docPath = path.resolve(__dirname, `../../config/targets/${targetId}.md`);
    if (fs.existsSync(docPath)) {
        try {
            return fs.readFileSync(docPath, "utf8");
        } catch {
            // fallback
        }
    }
    return `# Migration Instructions for ${targetId}\n\nGenerated by Lucerne.\n`;
}

module.exports = {
    rowsToCsvBuffer,
    rowsToXlsxBuffer,
    chunkRows,
    addFilesToZip,
    getMigrationInstructions,
};
